#!/bin/sh
# One-time setup of the three-VM cluster/HA test bed (plan §8.2), driven from
# the host. Idempotent: re-running reinstalls binaries, configs and units.
#
# Prerequisites:
#   - Lima >= 1.0 with the `user-v2` network (defined in the default
#     ~/.lima/_config/networks.yaml; no root, no socket_vmnet needed)
#   - VMs: plat-linux (existing, with `--network lima:user-v2` added),
#     plat-linux-2 and plat-edge from deploy/lima/*.yaml, all started
#   - an aarch64 Linux platd binary: PLATD_BIN (default
#     target/aarch64-unknown-linux-gnu/release/platd)
#
# Usage: deploy/tests/cluster/setup.sh
#
# Creates on every VM a VXLAN overlay `plha0` (VNI 205) over user-v2 with
# static addresses (lib.sh), persistent through a reboot (plat-overlay.service,
# needed by F2); on the edge the netns `cli`/`inet`, FRR, the witness and the
# SIEM sink; on the nodes FRR, the hooks, platd and its unit. The cluster PKI
# (throwaway test CA; serverAuth+clientAuth EKU) is generated on the edge.
set -eu
CASE=setup
# shellcheck source=deploy/tests/cluster/lib.sh
. "$(dirname "$0")/lib.sh"

PLATD_BIN=${PLATD_BIN:-$ROOT/target/aarch64-unknown-linux-gnu/release/platd}
[ -x "$PLATD_BIN" ] || { echo "setup: no platd binary at $PLATD_BIN (set PLATD_BIN)" >&2; exit 2; }
for v in "$A" "$B" "$E"; do
    vm_up "$v" || { echo "setup: VM $v is not running" >&2; exit 2; }
    vm "$v" "ip -4 -o addr show | grep -q ' 192\\.168\\.104\\.'" ||
        { echo "setup: $v has no user-v2 address (limactl edit $v --network lima:user-v2)" >&2; exit 2; }
done

# --- overlay (all VMs) --------------------------------------------------------
overlay_script() {
    # $1 = own overlay host number, $2 = role (node|edge), $3.. = peer VM names
    me=$1
    role=$2
    shift 2
    cat <<EOF
#!/bin/sh
# Generated by deploy/tests/cluster/setup.sh - test bed only.
set -eu
u2=\$(ip -4 -o addr show | awk '\$4 ~ /^192\\.168\\.104\\./ { split(\$4, a, "/"); print a[1]; exit }')
ip link del plha0 2>/dev/null || true
ip link add plha0 type vxlan id 205 dstport 4789 local "\$u2" nolearning
ip link set plha0 mtu 1450 up
ip addr add 192.168.205.$me/24 dev plha0
ip -6 addr add fd00:205::$me/64 dev plha0 nodad
for peer in $*; do
    i=0
    until addr=\$(getent ahostsv4 "lima-\$peer.internal" | awk 'NR == 1 { print \$1 }') && [ -n "\$addr" ]; do
        i=\$((i + 1)); [ \$i -lt 60 ] || { echo "cannot resolve lima-\$peer.internal" >&2; exit 1; }
        sleep 1
    done
    bridge fdb append 00:00:00:00:00:00 dev plha0 dst "\$addr"
done
EOF
    if [ "$role" = node ]; then
        cat <<EOF
ip -6 route replace 2001:db8:100::/40 via $E6
ip route replace 203.0.113.0/24 via $E_IP
EOF
    else
        cat <<'EOF'
sysctl -qw net.ipv4.ip_forward=1 net.ipv6.conf.all.forwarding=1 net.ipv6.fib_multipath_hash_policy=0
for ns in cli inet; do ip netns del $ns 2>/dev/null || true; ip netns add $ns; done
ip link del cli0 2>/dev/null || true   # re-run: the veths can outlive their netns
ip link del inet0 2>/dev/null || true
ip link add cli0 type veth peer name cli1 netns cli
ip link add inet0 type veth peer name inet1 netns inet
ip link set cli0 up
ip link set inet0 up
ip addr add 203.0.113.1/24 dev inet0
ip -n inet addr add 203.0.113.10/24 dev inet1
ip -n inet link set lo up
ip -n inet link set inet1 up
ip -n inet route add default via 203.0.113.1
ip -n cli link set lo up
ip -n cli link set cli1 up
n=1
while [ $n -le 8 ]; do
    ip -6 addr add "2001:db8:100:$n::1/64" dev cli0 nodad
    ip -6 -n cli addr add "2001:db8:100:$n::10/64" dev cli1 nodad
    n=$((n + 1))
done
ip -6 -n cli route add default via 2001:db8:100:1::1
EOF
    fi
}
install_overlay() {
    overlay_script "$2" "$3" "$4" "$5" >"$OUT/overlay-$1.sh"
    limactl copy "$OUT/overlay-$1.sh" "$1:/tmp/plat-overlay.sh"
    vm "$1" "install -m 0755 /tmp/plat-overlay.sh /usr/local/sbin/plat-overlay.sh
cat >/etc/systemd/system/plat-overlay.service <<'UNIT'
[Unit]
Description=usg-plat cluster test overlay (VXLAN over Lima user-v2)
After=network-online.target
Wants=network-online.target
Before=frr.service platd.service plat-witness.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/plat-overlay.sh

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload && systemctl enable plat-overlay.service && systemctl restart plat-overlay.service"
}
install_overlay "$A" 11 node "$B" "$E"
install_overlay "$B" 12 node "$A" "$E"
install_overlay "$E" 20 edge "$A" "$B"
vm "$A" "ping -c 2 -W 2 $B_IP >/dev/null && ping -c 2 -W 2 $E_IP >/dev/null" || { echo "setup: overlay not reachable" >&2; exit 1; }

# --- PKI (generated on the edge, OpenSSL 3) --------------------------------------
cat >"$OUT/pki.sh" <<'PKI'
set -e
d=/root/plat-pki
mkdir -p $d
cd $d
[ -f ca.key ] || { openssl ecparam -name prime256v1 -genkey -noout -out ca.key
    openssl req -x509 -new -key ca.key -sha256 -days 30 -subj "/CN=usg-plat cluster test CA" \
        -addext basicConstraints=critical,CA:TRUE -addext keyUsage=critical,keyCertSign,cRLSign -out ca.crt; }
for n in plat-1 plat-2 witness; do
    [ -f $n.crt ] && continue
    openssl ecparam -name prime256v1 -genkey -noout -out $n.key
    openssl req -new -key $n.key -subj "/CN=$n.cluster.example" -out $n.csr
    printf "basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth,clientAuth\nsubjectAltName=DNS:%s.cluster.example\n" $n >$n.ext
    openssl x509 -req -in $n.csr -CA ca.crt -CAkey ca.key -CAcreateserial -days 30 -sha256 -extfile $n.ext -out $n.crt
done
chmod 0644 /root/plat-pki/*.crt /root/plat-pki/*.key
PKI
limactl copy "$OUT/pki.sh" "$E:/tmp/plat-pki.sh"
vm "$E" "sh /tmp/plat-pki.sh"
mkdir -p "$OUT/pki"
for f in ca.crt plat-1.crt plat-1.key plat-2.crt plat-2.key witness.crt witness.key; do
    vm "$E" "cat /root/plat-pki/$f" >"$OUT/pki/$f"
done
vm "$E" "chmod 0600 /root/plat-pki/*.key"

# --- platd, hooks, unit, PKI on every VM -----------------------------------------
install_common() {
    limactl copy "$PLATD_BIN" "$1:/tmp/platd"
    limactl copy "$ROOT/deploy/systemd/plat-tun-setup.sh" "$1:/tmp/plat-tun-setup.sh"
    limactl copy "$ROOT/deploy/systemd/platd.service" "$1:/tmp/platd.service"
    limactl copy "$ROOT/deploy/systemd/plat.tmpfiles.conf" "$1:/tmp/plat.tmpfiles.conf"
    limactl copy "$ROOT/deploy/hooks/frr-announce.sh" "$1:/tmp/frr-announce.sh"
    limactl copy "$ROOT/deploy/hooks/frr-withdraw.sh" "$1:/tmp/frr-withdraw.sh"
    limactl copy "$OUT/pki/ca.crt" "$1:/tmp/ca.crt"
    limactl copy "$OUT/pki/$2.crt" "$1:/tmp/cluster.crt"
    limactl copy "$OUT/pki/$2.key" "$1:/tmp/cluster.key"
    vm "$1" "set -e
getent passwd plat >/dev/null || useradd --system --user-group --no-create-home --home-dir /nonexistent --shell /usr/sbin/nologin plat
getent group plat-log >/dev/null || groupadd --system plat-log
install -m 0755 /tmp/platd /usr/bin/platd
install -D -m 0755 /tmp/plat-tun-setup.sh /usr/libexec/plat/plat-tun-setup.sh
install -D -m 0755 -o root -g root /tmp/frr-announce.sh /usr/libexec/plat/frr-announce.sh
install -D -m 0755 -o root -g root /tmp/frr-withdraw.sh /usr/libexec/plat/frr-withdraw.sh
install -m 0644 /tmp/platd.service /etc/systemd/system/platd.service
install -D -m 0644 /tmp/plat.tmpfiles.conf /usr/lib/tmpfiles.d/plat.conf
systemd-tmpfiles --create /usr/lib/tmpfiles.d/plat.conf
install -d -m 0700 -o plat -g plat /var/lib/plat/cluster
install -D -m 0644 /tmp/ca.crt /etc/plat/tls/ca.crt
install -m 0644 /tmp/cluster.crt /etc/plat/tls/cluster.crt
install -m 0640 -o root -g plat /tmp/cluster.key /etc/plat/tls/cluster.key
usermod -aG frrvty plat
mkdir -p /opt/plat-test
rm -f /tmp/platd /tmp/cluster.key"
}
install_common "$A" plat-1
install_common "$B" plat-2
install_common "$E" witness

# --- FRR ------------------------------------------------------------------------
node_frr() {
    cat <<EOF
frr defaults traditional
hostname $1
!
bfd
 profile fast
  receive-interval 300
  transmit-interval 300
  detect-multiplier 3
 exit
exit
!
router bgp 64513
 bgp router-id $2
 no bgp ebgp-requires-policy
 no bgp default ipv4-unicast
 no bgp network import-check
 timers bgp 1 3
 neighbor $E_IP remote-as 64512
 neighbor $E_IP bfd profile fast
 neighbor $E6 remote-as 64512
 neighbor $E6 bfd profile fast
 address-family ipv4 unicast
  neighbor $E_IP activate
 exit-address-family
 address-family ipv6 unicast
  neighbor $E6 activate
 exit-address-family
exit
EOF
}
edge_frr() {
    cat <<EOF
frr defaults traditional
hostname plat-edge
!
bfd
 profile fast
  receive-interval 300
  transmit-interval 300
  detect-multiplier 3
 exit
exit
!
router bgp 64512
 bgp router-id $E_IP
 no bgp ebgp-requires-policy
 no bgp default ipv4-unicast
 timers bgp 1 3
 neighbor $A_IP remote-as 64513
 neighbor $A_IP bfd profile fast
 neighbor $B_IP remote-as 64513
 neighbor $B_IP bfd profile fast
 neighbor $A6 remote-as 64513
 neighbor $A6 bfd profile fast
 neighbor $B6 remote-as 64513
 neighbor $B6 bfd profile fast
 address-family ipv4 unicast
  neighbor $A_IP activate
  neighbor $B_IP activate
  maximum-paths 2
 exit-address-family
 address-family ipv6 unicast
  neighbor $A6 activate
  neighbor $B6 activate
  maximum-paths 2
 exit-address-family
exit
EOF
}
install_frr() {
    limactl copy "$2" "$1:/tmp/frr.conf"
    vm "$1" "install -m 0640 -o frr -g frr /tmp/frr.conf /etc/frr/frr.conf && systemctl restart frr"
}
# The NAT64 prefix is announced only while platd runs (ExecStopPost also
# runs after a crash/SIGKILL), and again after an FRR restart (D-1). Uses
# the shipped deploy/systemd/plat-v6-announce.sh and the example drop-ins.
v6_announce_dropins() {
    limactl copy "$ROOT/deploy/systemd/plat-v6-announce.sh" "$1:/tmp/plat-v6-announce.sh"
    limactl copy "$ROOT/deploy/systemd/platd.service.d.example/v6-announce.conf" "$1:/tmp/v6-announce.conf"
    limactl copy "$ROOT/deploy/systemd/frr.service.d.example/plat-v6-announce.conf" "$1:/tmp/frr-v6.conf"
    vm "$1" "set -e
install -d /usr/libexec/plat /etc/systemd/system/platd.service.d /etc/systemd/system/frr.service.d
install -m 0755 /tmp/plat-v6-announce.sh /usr/libexec/plat/plat-v6-announce.sh
printf 'PLAT_BGP_ASN=64513\\nPLAT_NAT64_PREFIX=64:ff9b:1::/96\\nPLAT_V6_MODE=cluster\\nPLAT_V4_POOL=\"$POOL\"\\n' >/etc/default/plat-v6-announce
rm -f /etc/systemd/system/platd.service.d/plat-test-v6.conf /etc/systemd/system/frr.service.d/plat-test-v6.conf
install -m 0644 /tmp/v6-announce.conf /etc/systemd/system/platd.service.d/v6-announce.conf
install -m 0644 /tmp/frr-v6.conf /etc/systemd/system/frr.service.d/plat-v6-announce.conf
systemctl daemon-reload"
}
v6_announce_dropins "$A"
v6_announce_dropins "$B"
node_frr plat-1 "$A_IP" >"$OUT/frr-a.conf"
node_frr plat-2 "$B_IP" >"$OUT/frr-b.conf"
edge_frr >"$OUT/frr-e.conf"
install_frr "$A" "$OUT/frr-a.conf"
install_frr "$B" "$OUT/frr-b.conf"
install_frr "$E" "$OUT/frr-e.conf"

# --- edge services: witness, traffic server, SIEM sink -----------------------------
# Witness configuration (`platd witness`, format in
# services/platd/src/cluster/witness.rs): the members, lease timing and
# identities must match the nodes' [cluster] / [cluster.ha] (digest checked).
cat >"$OUT/witness.toml" <<EOF
# Generated by deploy/tests/cluster/setup.sh - test bed only.
[witness]
name = "witness"
listen = "$E_IP:$PEER_PORT"
identity = "dns:witness.cluster.example"
lease_ms = $LEASE_MS
heartbeat_ms = 500
drift_margin_pct = $DRIFT_PCT
state_dir = "/var/lib/plat/witness"
members = [
    { id = 0, identity = "dns:plat-1.cluster.example", addr = "$A_IP:$PEER_PORT" },
    { id = 1, identity = "dns:plat-2.cluster.example", addr = "$B_IP:$PEER_PORT" },
]
[witness.tls]
cert_file = "/etc/plat/tls/cluster.crt"
key_file = "/etc/plat/tls/cluster.key"
ca_file = "/etc/plat/tls/ca.crt"
[tls.revocation]
mode = "off"   # test PKI without CRL/OCSP
[audit.file]   # required (AU-12); /var/log/plat from plat.tmpfiles.conf
path = "/var/log/plat/witness-audit.jsonl"
EOF
limactl copy "$OUT/witness.toml" "$E:/tmp/witness.toml"
limactl copy "$HERE/flows.py" "$E:/tmp/flows.py"
vm "$E" "set -e
install -m 0640 -o root -g plat /tmp/witness.toml /etc/plat/witness.toml
install -m 0755 /tmp/flows.py /opt/plat-test/flows.py
install -d -m 0750 /var/log/plat-siem
cat >/etc/systemd/system/plat-witness.service <<'UNIT'
[Unit]
Description=usg-plat cluster witness (test bed)
After=plat-overlay.service
[Service]
User=plat
StateDirectory=plat/witness
StateDirectoryMode=0700
ExecStart=/usr/bin/platd witness --config /etc/plat/witness.toml
Restart=on-failure
[Install]
WantedBy=multi-user.target
UNIT
cat >/etc/systemd/system/plat-flows-server.service <<'UNIT'
[Unit]
Description=usg-plat test traffic server (netns inet)
After=plat-overlay.service
[Service]
ExecStart=/usr/sbin/ip netns exec inet /usr/bin/python3 /opt/plat-test/flows.py server --bind $SERVER4
Restart=always
[Install]
WantedBy=multi-user.target
UNIT
cat >/etc/systemd/system/plat-siem.service <<'UNIT'
[Unit]
Description=usg-plat test SIEM sink (UDP syslog, JSON payloads)
After=plat-overlay.service
[Service]
ExecStart=/usr/bin/python3 /opt/plat-test/flows.py syslog --bind $E_IP --port 514 --out /var/log/plat-siem/siem.jsonl
Restart=always
[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable plat-witness plat-flows-server plat-siem
# restart: the overlay re-creates netns inet, a running server would stay in the old one
systemctl restart plat-witness plat-flows-server plat-siem"

# --- node configs and platd --------------------------------------------------------
restore_configs
for v in "$A" "$B"; do
    vm "$v" "platd check-config --config /etc/plat/platd.toml >/dev/null" || { echo "setup: check-config failed on $v" >&2; exit 1; }
    vm "$v" "systemctl daemon-reload && systemctl enable platd && systemctl restart platd"
done
ensure_cluster
info "test bed ready: A=$(active_slices "$A") B=$(active_slices "$B") active slices"
finish
